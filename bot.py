async def ask_ai(user_text, channel_id, context=""):
    history = conversation.setdefault(channel_id, [])

    full_text = f"{context}\nСообщение: {user_text}" if context else user_text
    history.append({"role": "user", "content": full_text})

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        *history[-15:]
    ]

    try:
        response = await deepseek.chat.completions.create(
            model="deepseek-chat",
            messages=messages,
            max_tokens=350,
            temperature=1.0
        )
    except Exception as e:
        print(f"DeepSeek ошибка: {e}")
        return None

    answer = (response.choices[0].message.content or "").strip()
    if not answer:
        return None

    history.append({"role": "assistant", "content": answer})
    return answer


def should_respond(message_content):
    content_lower = message_content.lower()
    for word in TRIGGER_WORDS:
        if word in content_lower:
            return True
    if len(message_content) > 20:
        return random.random() < 0.5
    return random.random() < 0.25


