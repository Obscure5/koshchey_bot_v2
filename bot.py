@bot.event
async def on_message(message):
    if message.author.bot:
        return

    if message.content.lower() in VOICE_COMMANDS:
        if message.author.voice and message.author.voice.channel:
            channel = message.author.voice.channel
            await message.channel.send(f"🔊 Захожу в голосовой канал {channel.name}...")
            await play_voice_phrase(channel)
        else:
            await message.channel.send("❌ Ты должен быть в голосовом канале, чтобы я зашёл!")
        return

    if bot.user in message.mentions:
        text = message.content
        text = text.replace(f"<@{bot.user.id}>", "").replace(f"<@!{bot.user.id}>", "").strip()
        if not text:
            text = "чё скажешь?"
        async with message.channel.typing():
            await asyncio.sleep(random.uniform(0.5, 1.5))
            answer = await ask_ai(text, message.channel.id) or random.choice(KOSHCHEY_PHRASES)
            await message.reply(answer[:2000])
        return

    if should_respond(message.content):
        async with message.channel.typing():
            await asyncio.sleep(random.uniform(1.0, 3.0))
            answer = await ask_ai(message.content, message.channel.id)
            if not answer:
                answer = random.choice(KOSHCHEY_PHRASES)
            if random.random() < 0.5:
                await message.reply(answer[:2000])
            else:
                await message.channel.send(answer[:2000])


